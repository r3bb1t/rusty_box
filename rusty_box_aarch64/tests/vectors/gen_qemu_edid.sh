#!/bin/sh
# Regenerate qemu_edid.txt: the EDID QEMU's virtio-gpu reports for a display
# of each size, from QEMU's own generator (hw/display/edid-generate.c) built
# with just enough of QEMU's headers to compile it.
#
#   tests/vectors/gen_qemu_edid.sh /path/to/qemu > tests/vectors/qemu_edid.txt
set -eu
qemu=$1
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/qemu" "$work/hw/display"
cat > "$work/qemu/osdep.h" <<'EOF'
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include <string.h>
#include <stdlib.h>
#include <stdio.h>
#define ARRAY_SIZE(x) (sizeof(x) / sizeof((x)[0]))
EOF
cat > "$work/qemu/bswap.h" <<'EOF'
static inline void stw_le_p(void *p, uint16_t v) { uint8_t *b = p; b[0] = v; b[1] = v >> 8; }
static inline void stw_be_p(void *p, uint16_t v) { uint8_t *b = p; b[0] = v >> 8; b[1] = v; }
static inline void stl_le_p(void *p, uint32_t v) { uint8_t *b = p; b[0] = v; b[1] = v >> 8; b[2] = v >> 16; b[3] = v >> 24; }
EOF
{
    echo 'typedef struct MemoryRegion MemoryRegion; typedef struct Object Object;'
    cat "$qemu/include/hw/display/edid.h"
} > "$work/hw/display/edid.h"
cat > "$work/main.c" <<'EOF'
#include "qemu/osdep.h"
#include "hw/display/edid.h"
/* virtio_gpu_base_generate_edid with no output name, physical size or
 * refresh rate: every other field of qemu_edid_info is zero. */
int main(int argc, char **argv)
{
    for (int i = 1; i + 1 < argc; i += 2) {
        uint8_t edid[1024];
        memset(edid, 0, sizeof(edid));
        qemu_edid_info info = { .prefx = atoi(argv[i]), .prefy = atoi(argv[i + 1]) };
        qemu_edid_generate(edid, sizeof(edid), &info);
        printf("%sx%s ", argv[i], argv[i + 1]);
        for (int j = 0; j < 1024; j++) {
            printf("%02x", edid[j]);
        }
        printf("\n");
    }
    return 0;
}
EOF
cc -O1 -I"$work" -o "$work/edidgen" "$work/main.c" "$qemu/hw/display/edid-generate.c"
echo "# EDID of QEMU's virtio-gpu, by display size: WIDTHxHEIGHT then 1024 bytes in hex."
echo "# Generated by gen_qemu_edid.sh from QEMU's hw/display/edid-generate.c."
"$work/edidgen" 640 480 800 600 1024 768 1280 800 1920 1080 2560 1440 3840 2160 4096 2160 5120 2880
